export interface CatalogueLoad {
  /** Validated recipes, indexed by identifier (identifiers are unique). */
  byId: ReadonlyMap<string, Recipe>;
  /** Validated recipes in file order. */
  recipes: readonly Recipe[];
}

/** The imported Wikilivres lot (generated by scripts/import-wikilivres.mjs). */
const WIKILIVRES = wikilivresFile as {
  recipes?: unknown[];
  licence?: string;
  source?: string;
};

/**
 * Validate the whole witness catalogue with the public recipe contract.
 * The validator is injected so this module stays importable under Node's
 * type-stripping test runner (runtime `.js` imports do not resolve there) —
 * the bridge and the tests both pass the same `parseRecipe`.
 * Throws (with the offending entry index) if an entry is invalid — the
 * catalogue is authored data, never untrusted input.
 */
export function loadCatalogue(
  parse: (input: unknown) => ParseRecipeResult,
): CatalogueLoad {
  if (!Array.isArray(WIKILIVRES.recipes)) {
    throw new Error("Catalogue Wikilivres illisible : `recipes` manquant dans catalogue-wikilivres.json.");
  }
  const allEntries = [...CATALOGUE_RAW, ...WIKILIVRES.recipes];
  const byId = new Map<string, Recipe>();
  const recipes: Recipe[] = [];
  for (const [i, raw] of allEntries.entries()) {
    const v = parse(raw);
    if (!v.ok) {
      throw new Error(`Entrée de catalogue témoin n°${i} invalide : ${v.error}`);
    }
    if (byId.has(v.recipe.id)) {
      throw new Error(`Identifiant de catalogue en doublon : ${v.recipe.id}`);
    }
    byId.set(v.recipe.id, v.recipe);
    recipes.push(v.recipe);
  }
  return { byId, recipes };
}
